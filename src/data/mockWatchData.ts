export function calculateTotalPrice(config: CustomWatchConfig): number {
  const currentCase = CASE_OPTIONS.find((c) => c.id === config.caseId) || CASE_OPTIONS[0];
  const currentDial = DIAL_OPTIONS.find((d) => d.id === config.dialId) || DIAL_OPTIONS[0];
  const currentHands = HANDS_OPTIONS.find((h) => h.id === config.handsId) || HANDS_OPTIONS[0];
  const currentStrap = STRAP_OPTIONS.find((s) => s.id === config.strapId) || STRAP_OPTIONS[0];

  return (
    BASE_WATCH_PRICE +
    currentCase.priceAdjustment +
    currentDial.priceAdjustment +
    currentHands.priceAdjustment +
    currentStrap.priceAdjustment
  );
}

export function formatPrice(egpAmount: number): string {
  return `${egpAmount.toLocaleString('en-US')} ${CURRENCY_SYMBOL}`;
}
